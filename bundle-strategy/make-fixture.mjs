#!/usr/bin/env node
/**
 * make-fixture.mjs — generate the bulky data modules the fixture app imports.
 *
 * Why generated rather than committed: the labs need modules whose SOURCE is genuinely large
 * (a bundler measures bytes, and `Array.from({length: 1500})` is only a few hundred bytes of
 * source however big it is at runtime). Generating them keeps the repo small and lets you
 * change the sizes to see how the numbers move.
 *
 *   node make-fixture.mjs            # default sizes
 *   node make-fixture.mjs --chart 120 --locale 40     # KB
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const kb = (name, dflt) => {
  const i = process.argv.indexOf(`--${name}`);
  return i === -1 ? dflt : Number(process.argv[i + 1]);
};

const CHART_KB = kb('chart', 90);
const LOCALE_KB = kb('locale', 30);

/** Literal data, so the bytes are real bytes in the source and therefore in the bundle. */
function literalRecords(targetKb, prefix) {
  const rows = [];
  let bytes = 0;
  for (let i = 0; bytes < targetKb * 1024; i++) {
    const row = `  { id: ${i}, key: "${prefix}-${i}", label: "${prefix} entry ${i} ${'-'.repeat(30)}", weight: ${(i * 7) % 100} },`;
    rows.push(row);
    bytes += row.length;
  }
  return rows.join('\n');
}

mkdirSync(join(here, 'src/vendor'), { recursive: true });
mkdirSync(join(here, 'src/lib'), { recursive: true });

writeFileSync(join(here, 'src/vendor/chart-data.js'),
`// GENERATED by make-fixture.mjs — the bulk of the "charting library".
export const KERNELS = [
${literalRecords(CHART_KB, 'kernel')}
];
export const version = '2.4.0';
`);

writeFileSync(join(here, 'src/lib/locale-data.js'),
`// GENERATED by make-fixture.mjs — the bulk of the "date library".
export const LOCALE_DATA = [
${literalRecords(LOCALE_KB, 'locale')}
];
`);

console.log(`generated src/vendor/chart-data.js (~${CHART_KB}KB) and src/lib/locale-data.js (~${LOCALE_KB}KB)`);
console.log('these are gitignored; regenerate with different sizes to see how the numbers move.');
